-- 2026-11-12: Folder Bank Soal (tampilan seperti file explorer)
--
-- Tujuan:
--   Guru bisa merapikan bank soal ke dalam folder bertingkat (maks 3 level),
--   memindahkan soal antar folder, dan mencari folder/soal — seperti Windows Explorer.
--
-- Prinsip:
--   - `bank_soal.mapel` TIDAK diubah/dihapus. mapel tetap dipakai jadwal ujian,
--     koreksi nilai, analisis, dan laporan. Folder hanya untuk penataan/arsip.
--   - Folder lama dibuat otomatis: satu folder root per pasangan (created_by, mapel),
--     lalu `folder_id` semua soal lama diisi. Setelah migrasi daftar langsung rapi.
--   - Hapus folder TIDAK menghapus soal: FK `folder_id` ON DELETE SET NULL
--     (soal kembali ke root). UI tetap menanyakan konfirmasi sebelum menghapus.
--   - Kedalaman 3 level dijaga trigger database, bukan hanya UI.
--   - Tulis hanya lewat edge function `admin-proxy` (service_role); RLS hanya
--     mengizinkan SELECT (sama seperti bank_soal) agar admin panel bisa membaca.

-- ============================================================
-- 1. TABEL FOLDER
-- ============================================================
CREATE TABLE IF NOT EXISTS public.bank_soal_folder (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama       text NOT NULL,
  parent_id  bigint REFERENCES public.bank_soal_folder(id) ON DELETE CASCADE,
  created_by integer REFERENCES public.guru(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_bank_soal_folder_parent
  ON public.bank_soal_folder(parent_id);
CREATE INDEX IF NOT EXISTS idx_bank_soal_folder_created_by
  ON public.bank_soal_folder(created_by);

-- Nama folder unik dalam satu induk + satu pembuat (case-insensitive).
-- COALESCE dipakai karena UNIQUE biasa tidak menahan duplikat saat parent_id NULL.
CREATE UNIQUE INDEX IF NOT EXISTS uq_bank_soal_folder_nama
  ON public.bank_soal_folder(created_by, COALESCE(parent_id, 0), lower(nama));

-- ============================================================
-- 2. TRIGGER: MAKSIMAL 3 LEVEL + ANTI FOLDER MELINGKAR
-- ============================================================
CREATE OR REPLACE FUNCTION public.bank_soal_folder_cek()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_parent bigint := NEW.parent_id;
  v_depth  int := 1;
  v_guard  int := 0;
BEGIN
  IF v_parent IS NOT NULL AND NEW.id IS NOT NULL AND v_parent = NEW.id THEN
    RAISE EXCEPTION 'Folder tidak boleh menjadi induk dirinya sendiri'
      USING ERRCODE = 'check_violation';
  END IF;

  WHILE v_parent IS NOT NULL LOOP
    v_depth := v_depth + 1;
    IF v_depth > 3 THEN
      RAISE EXCEPTION 'Folder maksimal 3 tingkat'
        USING ERRCODE = 'check_violation';
    END IF;
    IF TG_OP = 'UPDATE' AND NEW.id IS NOT NULL AND v_parent = NEW.id THEN
      RAISE EXCEPTION 'Folder tidak boleh dipindah ke dalam subfoldernya sendiri'
        USING ERRCODE = 'check_violation';
    END IF;

    SELECT f.parent_id INTO v_parent
    FROM public.bank_soal_folder f
    WHERE f.id = v_parent;

    v_guard := v_guard + 1;
    IF v_guard > 10 THEN
      RAISE EXCEPTION 'Struktur folder terlalu dalam atau melingkar'
        USING ERRCODE = 'check_violation';
    END IF;
  END LOOP;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_bank_soal_folder_cek ON public.bank_soal_folder;
CREATE TRIGGER trg_bank_soal_folder_cek
  BEFORE INSERT OR UPDATE OF parent_id ON public.bank_soal_folder
  FOR EACH ROW EXECUTE FUNCTION public.bank_soal_folder_cek();

-- ============================================================
-- 3. KOLOM folder_id DI bank_soal
-- ============================================================
ALTER TABLE public.bank_soal
  ADD COLUMN IF NOT EXISTS folder_id bigint
  REFERENCES public.bank_soal_folder(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_bank_soal_folder_id
  ON public.bank_soal(folder_id);

-- ============================================================
-- 4. BACKFILL: folder root per (created_by, mapel) + isi folder_id
-- ============================================================
-- NULL harus di-cast eksplisit: dengan DISTINCT, NULL tanpa tipe dianggap text
-- sehingga INSERT ke parent_id (bigint) gagal dengan error 42804.
INSERT INTO public.bank_soal_folder (nama, parent_id, created_by)
SELECT DISTINCT trim(b.mapel), NULL::bigint, COALESCE(b.created_by, 1)
FROM public.bank_soal b
WHERE b.mapel IS NOT NULL
  AND trim(b.mapel) <> ''
ON CONFLICT DO NOTHING;

UPDATE public.bank_soal b
SET folder_id = f.id
FROM public.bank_soal_folder f
WHERE b.folder_id IS NULL
  AND f.parent_id IS NULL
  AND f.created_by = COALESCE(b.created_by, 1)
  AND lower(f.nama) = lower(trim(b.mapel));

-- ============================================================
-- 5. RLS + GRANT (baca boleh, tulis hanya lewat admin-proxy)
-- ============================================================
ALTER TABLE public.bank_soal_folder ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS bank_folder_select ON public.bank_soal_folder;
CREATE POLICY bank_folder_select ON public.bank_soal_folder
  FOR SELECT USING (true);

REVOKE INSERT, UPDATE, DELETE ON public.bank_soal_folder FROM anon, authenticated;
GRANT SELECT ON public.bank_soal_folder TO anon, authenticated;
GRANT ALL ON public.bank_soal_folder TO service_role;

-- Id kolom membuat sequence bank_soal_folder_id_seq; service_role butuh USAGE
-- supaya insert lewat admin-proxy tidak gagal "permission denied for sequence".
DO $$
BEGIN
  IF to_regclass('public.bank_soal_folder_id_seq') IS NOT NULL THEN
    EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.bank_soal_folder_id_seq TO service_role';
  END IF;
END $$;

NOTIFY pgrst, 'reload schema';
